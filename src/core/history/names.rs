pub fn clean_title(raw: &str) -> String {
    raw.chars()
        .filter(|&c| !is_invisible(c))
        .collect::<String>()
        .trim()
        .to_string()
}

pub fn name_key(raw: &str) -> String {
    let text: String = raw.nfkc().collect();
    let visible: String = text
        .chars()
        .filter(|&c| !is_invisible(c) && !is_variation(c) && !c.is_whitespace())
        .collect();
    let key: String = visible.chars().filter(|&c| !is_so_sk_cf(c)).collect();
    if key.is_empty() { visible } else { key }
}

pub fn candidate_names(entry: &Value) -> Vec<String> {
    let mut result = Vec::new();
    if let Some(recipient) = entry.get("recipient").and_then(|v| v.as_str()) {
        result.push(recipient.to_string());
    }
    if let Some(aliases) = entry.get("aliases").and_then(|v| v.as_array()) {
        for alias in aliases {
            if let Some(s) = alias.as_str() {
                result.push(s.to_string());
            }
        }
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn test_names_emoji_and_symbols_removed() {
        assert_eq!(name_key("🍓小美丨鞋"), name_key("小美丨鞋"));
        assert_eq!(name_key("✨Ａｂｃ ★"), "Abc");
    }

    #[test]
    fn test_names_invisible_characters_removed() {
        assert_eq!(name_key("小\u{200B}美\u{FE0F}"), "小美");
    }

    #[test]
    fn test_names_all_symbol_name_falls_back() {
        assert_eq!(name_key("🍓🍓"), "🍓🍓");
    }

    #[test]
    fn test_names_clean_title_keeps_symbols() {
        assert_eq!(clean_title(" \u{200B}🍓小美 "), "🍓小美");
    }

    #[test]
    fn test_names_candidate_names() {
        let entry1 = json!({"recipient": "a", "kind": "private", "aliases": ["b"]});
        assert_eq!(candidate_names(&entry1), vec!["a", "b"]);

        let entry2 = json!({"recipient": "a", "kind": "private"});
        assert_eq!(candidate_names(&entry2), vec!["a"]);
    }
}
